/** 日期补零：5 → '05' */
function pad(n) {
  return n < 10 ? '0' + n : String(n);
}

// 测试预览：想提前看某个节气/节日的海报效果，把下面改成日期（如 '2026-09-07' 看白露），
// 看完记得改回空字符串。留空 = 按真实日期走。
const PREVIEW_DATE = '';

/**
 * 取开屏内容：节日 > 节气 > 无（返回 null，页面退回每日禅语）
 * @param {Number} [ts] 时间戳，默认当前
 * @returns {{tag: string, quote: string} | null}
 */
function getSpecialContent(ts) {
  let dateStr;
  if (PREVIEW_DATE) {
    dateStr = PREVIEW_DATE;
  } else {
    const d = new Date(ts || Date.now());
    dateStr = d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate());
  }
  const year = dateStr.slice(0, 4);
  const md = dateStr.slice(5);

  const fest = (FESTIVALS[year] || {})[md];
  if (fest) return { tag: fest, quote: SPECIAL_QUOTES[fest] };

  const term = (SOLAR_TERMS[year] || {})[md];
  if (term) return { tag: term + ' · 节气', quote: SPECIAL_QUOTES[term] };

  return null;
}

module.exports = { getSpecialContent };
