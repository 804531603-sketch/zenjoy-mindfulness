/** 总天数（一年一循环） */
const TOTAL_DAYS = DAILY.length;

/**
 * 按日期取当天内容（1 月 1 日 = 第 1 天；一年一轮回）
 * @returns {Object} { day, title, reminder, thought, practice }
 */
function getDailyByDate(ts) {
  const d = new Date(ts || Date.now());
  const dayOfYear = Math.floor(
    (d - new Date(d.getFullYear(), 0, 0)) / 86400000
  );
  const idx = (dayOfYear - 1) % TOTAL_DAYS;
  return Object.assign({ day: idx + 1 }, DAILY[idx]);
}

